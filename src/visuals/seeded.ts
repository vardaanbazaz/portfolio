/** A small seeded generator (mulberry32): the same seed gives the same numbers on every load. Plain arithmetic, no
 *  scene code, so the About page's canopy and the grove's backdrops can both use it. */
export function seeded(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let r = Math.imul(a ^ (a >>> 15), 1 | a);
    r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}
